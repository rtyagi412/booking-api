-- Schema as created by Hibernate ddl-auto=update before Flyway (verified against the live database).
create table accounts (
    id bigint generated by default as identity,
    email varchar(32) not null,
    name varchar(32) not null,
    password_hash varchar(255) not null,
    role varchar(16) not null check (role in ('CUSTOMER', 'MANAGER', 'ADMIN')),
    primary key (id)
);
alter table accounts add constraint uk_accounts_email unique (email);
